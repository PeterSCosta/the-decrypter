const SYM_TO_NUM = new Map<string, number>();
ELEMENTS.forEach((s, i) => {
  if (s) SYM_TO_NUM.set(s.toUpperCase(), i);
});

export const decoders = mapDecoder({
  id: "periodic-table",
  name: "Tabela periódica",
  category: "transform",
  decode(input) {
    const tokens = input
      .trim()
      .split(/[\s,.\-]+/)
      .filter(Boolean);
    if (tokens.length === 0) return null;

    if (tokens.every((t) => /^\d{1,3}$/.test(t) && +t >= 1 && +t <= 118)) {
      return {
        output: tokens.map((t) => ELEMENTS[+t]).join(" "),
        notes: "números atômicos → símbolos",
        forcedScore: 0.7,
      };
    }
    const up = tokens.map((t) => t.toUpperCase());
    if (up.every((t) => SYM_TO_NUM.has(t))) {
      return {
        output: up.map((t) => SYM_TO_NUM.get(t)).join(" "),
        notes: "símbolos → números atômicos",
        forcedScore: 0.7,
      };
    }
    return null;
  },
});
